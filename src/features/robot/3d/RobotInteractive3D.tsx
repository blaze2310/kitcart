
"use client";

import {
  useCallback,
  useEffect,
  useRef,
  useState,
} from "react";
import { useGLTF } from "@react-three/drei";
import type { ThreeEvent } from "@react-three/fiber";

import type { Expression } from "@/features/robot/2d/robot-face";
import Robot3D, {
  type RobotActionRequest,
} from "./Robot3D";
import {
  getRobotAnimationUrl,
  type RobotAnimationId,
} from "./animation/animationRegistry";

const MAX_CLICK_GAP_MS = 400;
const CLICKS_FOR_SHY = 6;
const HAPPY_DURATION_MS = 1500;

type Phase = "idle" | "loading-shy" | "shy";

export type RobotInteractive3DProps = {
  onReaction?: (reaction: string) => void;
};

export default function RobotInteractive3D({
  onReaction,
}: RobotInteractive3DProps) {
  const [request, setRequest] =
    useState<RobotActionRequest>({
      id: "idle",
      serial: 0,
      mode: "loop",
    });

  const [expression, setExpression] =
    useState<Expression>("normal");

  const phaseRef = useRef<Phase>("idle");
  const consecutiveClicks = useRef(0);
  const lastClickTime = useRef<number | null>(null);

  const happyTimer = useRef<
    ReturnType<typeof setTimeout> | null
  >(null);

  const clearHappyTimer = useCallback(() => {
    if (happyTimer.current !== null) {
      clearTimeout(happyTimer.current);
      happyTimer.current = null;
    }
  }, []);

  const resetSequence = useCallback(() => {
    consecutiveClicks.current = 0;
    lastClickTime.current = null;
  }, []);

  const handleRobotClick = useCallback(
    (event: ThreeEvent<MouseEvent>) => {
      // Ignore clicks generated by dragging the model.
      if (event.delta > 5) return;

      // While Shy is loading or playing, do not
      // restart it or count another click sequence.
      if (phaseRef.current !== "idle") return;

      event.stopPropagation();

      const now = performance.now();
      const previous = lastClickTime.current;

      const rapid =
        previous !== null &&
        now - previous <= MAX_CLICK_GAP_MS;

      consecutiveClicks.current = rapid
        ? consecutiveClicks.current + 1
        : 1;

      lastClickTime.current = now;

      if (
        consecutiveClicks.current >= CLICKS_FOR_SHY
      ) {
        clearHappyTimer();
        resetSequence();

        phaseRef.current = "loading-shy";

        // Shy facial expression is set ONLY when
        // the actual Shy GLB action begins.
        setRequest((current) => ({
          id: "shy",
          mode: "once",
          serial: current.serial + 1,
        }));

        onReaction?.("Rapid clicks → Shy requested");
        return;
      }

      // One or two rapid clicks: Happy face while
      // the original Idle body animation continues.
      setExpression("happy");
      onReaction?.(
        `Happy (${consecutiveClicks.current}/${CLICKS_FOR_SHY} clicks)`
      );

      clearHappyTimer();

      happyTimer.current = setTimeout(() => {
        happyTimer.current = null;

        if (phaseRef.current === "idle") {
          setExpression("normal");
        }
      }, HAPPY_DURATION_MS);
    },
    [clearHappyTimer, resetSequence, onReaction]
  );

  const handleActionStarted = useCallback(
    (id: RobotAnimationId, face: Expression) => {
      if (id === "shy") {
        phaseRef.current = "shy";
        clearHappyTimer();
        setExpression("loved");
        onReaction?.("Shy playing + Loved expression");
        return;
      }

      if (id === "idle") {
        phaseRef.current = "idle";
        resetSequence();
        setExpression(face);
        onReaction?.("Idle");
      }
    },
    [clearHappyTimer, resetSequence, onReaction]
  );

  const handleActionCompleted = useCallback(
    (id: RobotAnimationId) => {
      if (id === "shy") {
        onReaction?.("Shy completed → Returning to Idle");
      }
    },
    [onReaction]
  );

  useEffect(() => {
    return () => {
      clearHappyTimer();
    };
  }, [clearHappyTimer]);

  return (
    <group onClick={handleRobotClick}>
      <Robot3D
        request={request}
        expression={expression}
        autoBlink
        tracking
        onActionStarted={handleActionStarted}
        onActionCompleted={handleActionCompleted}
      />
    </group>
  );
}

// Preload only the action needed for this interaction,
// not the entire library of future Pet Mode animations.
useGLTF.preload(getRobotAnimationUrl("shy"));
