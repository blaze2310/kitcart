BEGIN;

CREATE TABLE IF NOT EXISTS public.catalogue_products (
    id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    title text NOT NULL CHECK (btrim(title) <> ''),
    category_group text NOT NULL CHECK (btrim(category_group) <> ''),
    subcategory text NOT NULL CHECK (btrim(subcategory) <> ''),
    category text NOT NULL CHECK (btrim(category) <> ''),
    product_type text NOT NULL CHECK (product_type IN ('analytics', 'automation', 'website', 'slides')),
    price_inr integer NOT NULL CHECK (price_inr >= 0),
    creator text NOT NULL CHECK (btrim(creator) <> ''),
    description text NOT NULL,
    demo_cover boolean NOT NULL DEFAULT false,
    sort_position integer NOT NULL DEFAULT 0 CHECK (sort_position >= 0),
    is_published boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS catalogue_products_published_order_idx
    ON public.catalogue_products (sort_position, id)
    WHERE is_published;

COMMIT;
